// ---------------------------------------------------------------- падежные окончания («Выберите окончание»)
// после основы на согласный; они же после мн. числа -եր / -ներ
const SUFFIX_GROUP = {
  'ի': 'gen', 'ին': 'dat', 'ից': 'abl', 'ով': 'ins', 'ում': 'loc',
  'երի': 'gen', 'երին': 'dat', 'երից': 'abl', 'երով': 'ins', 'երում': 'loc',
  'ների': 'gen', 'ներին': 'dat', 'ներից': 'abl', 'ներով': 'ins', 'ներում': 'loc',
};
const BASE_SUFFIXES = ['ի', 'ին', 'ից', 'ով', 'ում'];
const PLURAL_SUFFIXES = { 'եր': ['երի', 'երին', 'երից', 'երով', 'երում'], 'ներ': ['ների', 'ներին', 'ներից', 'ներով', 'ներում'] };
export const SUFFIX = {
  re: /^([ա-և]+)/,                                   // окончание сразу после слова в примере
  group: SUFFIX_GROUP,                               // окончание (строчными) → падеж
  stemOk: (stem) => /[^աեէըիոօ]$/.test(stem),       // после гласной окончания другие (Աննայի) — только основы на согласный
  pool: (suffix) => {                                // окончания того же числа
    const pl = suffix.startsWith('ներ') ? 'ներ' : suffix.startsWith('եր') ? 'եր' : null;
    return pl ? PLURAL_SUFFIXES[pl] : BASE_SUFFIXES;
  },
};

