// ---------------------------------------------------------------- буквы и плитки
// Плитка — одна буква алфавита: «ու» — одна плитка; знаки ՞ ՛ ՜ прилипают к предыдущей букве.
export function mergeTile(ch, last) {
  if ((ch === 'ւ' || ch === 'Ւ') && last && !last.space && /^[ոՈ]$/.test(last.ch)) return true;
  if (/[՞՛՜]/.test(ch) && last && !last.space) return true;
  return false;
}
// есть ли в строке буква (плитка-буква, а не знак препинания)
export const HAS_LETTER = /[ա-ևԱ-Ֆ]/;
// плитка — буква (для «Собери слово»: все плитки слова должны быть буквами)
export const isLetterTile = (t) => !t.space && /^[ա-ևԱ-Ֆ]/.test(t.ch);
// буква плитки без знаков ՞ ՛ ՜ (для сравнения и замены)
export function tileBase(ch) { return String(ch || '').replace(/[՞՛՜]/g, ''); }
// что остаётся от плитки после замены буквы (знаки ՞ ՛ ՜)
export function tileTail(ch) { return String(ch).slice(tileBase(ch).length); }
// слово целиком из букв (игры «Угадай слово» и «Филворд»)
export const GUESS_WORD = /^[ա-ևԱ-Ֆ՞՛՜-]+$/;
export const FILWORD_CELL = /^[ա-ևԱ-Ֆ]+$/;
// слово из предложения без знаков по краям (։ ՝ , « » и т. п.); ՞ и ՛ внутри слова остаются
export const cleanWord = (w) => w.replace(/^[^ա-ֆԱ-Ֆ]+|[^ա-ֆԱ-Ֆ]+$/g, '');

